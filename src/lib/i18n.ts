const dictionaries: Record<Locale, Record<keyof typeof fr, string>> = { fr, en }

export type TranslationKey = keyof typeof fr

export function translate(locale: Locale, key: TranslationKey, vars?: Record<string, string | number>): string {
  const template = dictionaries[locale][key] ?? dictionaries.fr[key] ?? key
  if (!vars) return template
  return template.replace(/\{(\w+)\}/g, (_, name) => String(vars[name] ?? ''))
}

